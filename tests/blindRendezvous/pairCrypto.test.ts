describe("established pair-flight AEAD", () => {
  test("round-trips the exact state-selected slot without consuming caller secrets", async () => {
    const baseSecret = filled(0x70);
    const originalBaseSecret = Uint8Array.from(baseSecret);
    const prebinding = establishedPrebinding();
    const originalNonce = Uint8Array.from(prebinding.nonce!);
    const plaintext = await checkpointPlaintext();
    const sealed = await sealPairStepV1({
      module,
      baseSecret,
      expectedSlot: checkpointSlot(),
      prebinding,
      plaintext,
      roomPqMode: ROOM_PQ_MODE,
    });

    const opened = await openPairStepV1({
      module,
      baseSecret,
      expectedSlot: checkpointSlot(),
      prebinding,
      envelope: sealed.envelope,
      operationPayloadClass: 0,
      roomPqMode: ROOM_PQ_MODE,
    });
    expect(opened).not.toBeNull();
    expect(opened!.plaintext).toEqual(plaintext);
    expectBytesEqual(
      opened!.binding.pairRoutingTag,
      sealed.binding.pairRoutingTag,
    );
    expect(baseSecret).toEqual(originalBaseSecret);
    expect(prebinding.nonce).toEqual(originalNonce);
    expect(sealed.envelope.bootstrapHeader).toBeNull();
    expect(sealed.envelope.nonce).not.toBeNull();
    expect(sealed.envelope.pairCiphertextAndTag.length).toBe(4_033);
    expect(hex(sealed.binding.pairRoutingTag)).toBe(ESTABLISHED_KAT.routingTag);
    expect(hex(sealed.binding.semanticSlot)).toBe(ESTABLISHED_KAT.semanticSlot);
    expect(await sha256Hex(await pairAad(sealed.binding))).toBe(
      ESTABLISHED_KAT.aadSha256,
    );
    expect(
      await sha256Hex(
        await encodePairPlaintextV1(plaintext, 0, false, ROOM_PQ_MODE),
      ),
    ).toBe(ESTABLISHED_KAT.plaintextSha256);
    expect(await sha256Hex(sealed.envelope.pairCiphertextAndTag)).toBe(
      ESTABLISHED_KAT.ciphertextSha256,
    );
    expect(hex(sealed.envelope.pairCiphertextAndTag.slice(0, 32))).toBe(
      ESTABLISHED_KAT.ciphertextPrefix,
    );
    expect(hex(sealed.envelope.pairCiphertextAndTag.slice(-32))).toBe(
      ESTABLISHED_KAT.ciphertextSuffix,
    );
  });

  test("fails closed for wrong slots, tags, ciphertext, and nonce relocation", async () => {
    const baseSecret = filled(0x70);
    const prebinding = establishedPrebinding();
    const sealed = await sealPairStepV1({
      module,
      baseSecret,
      expectedSlot: checkpointSlot(),
      prebinding,
      plaintext: await checkpointPlaintext(),
      roomPqMode: ROOM_PQ_MODE,
    });
    const open = (
      expectedSlot: PairFlightSlotV1,
      envelope: typeof sealed.envelope,
      exactPrebinding = prebinding,
    ) =>
      openPairStepV1({
        module,
        baseSecret,
        expectedSlot,
        prebinding: exactPrebinding,
        envelope,
        operationPayloadClass: 0,
        roomPqMode: ROOM_PQ_MODE,
      });

    expect(
      await open({ ...checkpointSlot(), pairSequence: 3n }, sealed.envelope),
    ).toBeNull();

    const wrongTag = {
      ...sealed.envelope,
      pairRoutingTag: Uint8Array.from(sealed.envelope.pairRoutingTag),
    };
    wrongTag.pairRoutingTag[0] ^= 1;
    expect(await open(checkpointSlot(), wrongTag)).toBeNull();

    const wrongCiphertext = {
      ...sealed.envelope,
      pairCiphertextAndTag: Uint8Array.from(
        sealed.envelope.pairCiphertextAndTag,
      ),
    };
    wrongCiphertext.pairCiphertextAndTag[
      wrongCiphertext.pairCiphertextAndTag.length - 1
    ] ^= 1;
    expect(await open(checkpointSlot(), wrongCiphertext)).toBeNull();

    const relocated = {
      ...prebinding,
      nonce: Uint8Array.from(prebinding.nonce!),
    };
    relocated.nonce[0] ^= 1;
    await expect(
      open(checkpointSlot(), sealed.envelope, relocated),
    ).rejects.toThrow("nonce does not match its outer prebinding");
  });

  test("rejects a plaintext that disagrees with the expected slot before sealing", async () => {
    await expect(
      sealPairStepV1({
        module,
        baseSecret: filled(0x70),
        expectedSlot: { ...checkpointSlot(), pairSequence: 3n },
        prebinding: establishedPrebinding(),
        plaintext: await checkpointPlaintext(),
        roomPqMode: ROOM_PQ_MODE,
      }),
    ).rejects.toThrow(
      "pair plaintext does not match the expected pair flight slot",
    );
  });
});
